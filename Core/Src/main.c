float Calculate_Current(uint16_t adc_value)
{
  float voltage = abs(adc_value - OFFSET) * VREF / ADC_RESOLUTION; // Convert ADC value to voltage
  float curr = voltage / (R_SHUNT * GAIN);                         // Calculate current using Ohm's Law
  return curr;
}
void Transmit_CAN(uint16_t adc_amp1, uint16_t adc_amp2, uint16_t adc_amp3)
{

  float current_amp1 = Calculate_Current(adc_amp1) * 10;
  float current_amp2 = Calculate_Current(adc_amp2) * 10;
  float current_amp3 = Calculate_Current(adc_amp3) * 10;

  int curr1_int = (int)current_amp1;
  int curr2_int = (int)current_amp2;
  int curr3_int = (int)current_amp3;

  TxData[0] = (uint8_t)(curr1_int >> 8);
  TxData[1] = (uint8_t)(curr1_int & 0xFF);
  TxData[2] = (uint8_t)(curr2_int >> 8);
  TxData[3] = (uint8_t)(curr2_int & 0xFF);
  TxData[4] = (uint8_t)(curr3_int >> 8);
  TxData[5] = (uint8_t)(curr3_int & 0xFF);
}

